"""Keep the `none` column examined, not just asserted.

`BASIS.md` publishes five checks with no external basis. That is an honest answer
to "who required this?" and a dishonest one to "did you look?". This tool holds
the second question to a record:

    basis/none.json         per check: searches run, nearest neighbour, status
    basis/proposals/*.md    an issue draft for a `none` worth proposing

Rules:

    N1  every check that basis.json calls `none` has an entry, and no entry
        names a check that is not `none`
    N2  every entry carries at least one search with a query and a date
    N3  status `proposal-drafted` requires a proposal file that exists, is
        non-trivial, and contains a "What we ask" section
    N4  status `external-basis-found` requires a URL for the document found and
        a proposed class - finding is not a feeling
    N5  NONE.md is regenerated and byte-compared

    python tools/check_none.py            # verify, print one line, exit 0/1
    python tools/check_none.py --write    # regenerate NONE.md only
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASIS = ROOT / "basis.json"
NONE = ROOT / "basis" / "none.json"
OUT = ROOT / "NONE.md"
MIN_PROPOSAL = 800

STATUS = {
    "no-external-text-found": "looked, found nothing that requires it",
    "proposal-drafted": "looked, found no requirement, drafted one",
    "external-basis-found": "looked, found a basis: reclassify upstream",
}


def load(p):
    return json.loads(p.read_text(encoding="utf-8"))


def problems(bdoc, ndoc):
    probs = []
    none_ids = {c["id"] for c in bdoc["checks"] if c["class"] == "none"}
    entries = {e["check"]: e for e in ndoc["checks"]}
    for cid in sorted(none_ids - set(entries)):
        probs.append(f"N1: {cid} is published as none but has no record of what was searched")
    for cid in sorted(set(entries) - none_ids):
        probs.append(f"N1: {cid} has a none record but is not published as none")
    for e in ndoc["checks"]:
        cid = e["check"]
        if e.get("status") not in STATUS:
            probs.append(f"N2: {cid} has unknown status {e.get('status')!r}")
        searches = e.get("searches") or []
        if not searches:
            probs.append(f"N2: {cid} records no search")
        for s in searches:
            if not s.get("query") or not s.get("on") or not s.get("result"):
                probs.append(f"N2: {cid} has a search missing query, date or result")
        if e.get("status") == "proposal-drafted":
            p = e.get("proposal")
            if not p:
                probs.append(f"N3: {cid} claims a proposal but names no file")
                continue
            f = ROOT / p
            if not f.exists():
                probs.append(f"N3: {cid} proposal {p} does not exist")
            elif len(f.read_text(encoding="utf-8")) < MIN_PROPOSAL:
                probs.append(f"N3: {cid} proposal {p} is too thin to be a draft")
            elif "What we ask" not in f.read_text(encoding="utf-8"):
                probs.append(f"N3: {cid} proposal {p} has no 'What we ask' section")
        if e.get("status") == "external-basis-found":
            if not (e.get("nearest") or {}).get("url"):
                probs.append(f"N4: {cid} claims an external basis with no document URL")
            if e.get("proposed_class") not in ("direct", "related"):
                probs.append(f"N4: {cid} claims an external basis but proposes no class")
    return probs, none_ids


def render(bdoc, ndoc, none_ids):
    entries = {e["check"]: e for e in ndoc["checks"]}
    lines = [
        "# The `none` column — what we looked for before calling it ours",
        "",
        "Generated by `tools/check_none.py` from `basis/none.json`. `BASIS.md` says five checks",
        "have no external basis. That answers *who required it*; it does not answer *did you look*.",
        "This file answers the second question, per check, with the searches and the nearest",
        "neighbour found.",
        "",
        f"{len(none_ids)} check(s) with no external basis, reviewed {ndoc.get('reviewed_on')}.",
        "",
        "| check | name | status | nearest document | why it does not cover the rule |",
        "|---|---|---|---|---|",
    ]
    for cid in sorted(none_ids):
        e = entries[cid]
        near = e.get("nearest") or {}
        why = (near.get("why_not") or "—").replace("|", "\\|")
        lines.append(f"| {cid} | {e.get('name', '')} | `{e['status']}` | "
                     f"{near.get('doc', '—')} | {why} |")
    lines += ["", "Status meanings:", ""]
    for k, v in STATUS.items():
        lines.append(f"- `{k}` — {v}")
    lines += ["", "## Searches, verbatim", ""]
    for cid in sorted(none_ids):
        e = entries[cid]
        lines.append(f"### {cid} — {e.get('name', '')}")
        lines.append("")
        for s in e.get("searches", []):
            lines.append(f"- {s['on']} · `{s['query']}` → {s['result']}")
        if e.get("note"):
            lines += ["", e["note"]]
        if e.get("proposal"):
            lines += ["", f"Proposal: [`{e['proposal']}`]({e['proposal']}) — draft, not sent."]
        if e.get("upstream"):
            lines += ["", f"Reclassification needs an upstream change: `{e['upstream']}`."]
        lines.append("")
    lines += [
        "## What this file does not say",
        "",
        "It does not say the searches were exhaustive. Two queries per check, run on one day,",
        "is a floor: it catches the case where we said *nobody requires this* while a requirement",
        "sat in a draft we already cite. It cannot catch what nobody has written yet.",
        "",
        "It does not turn a `none` into a `related`. Only a document that states the mechanism",
        "can do that, and the class lives in the verifier, not here.",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def selftest(bdoc, ndoc):
    """Five mutations of the record, each of which must be caught."""
    import copy
    cases = []

    def mutate(name, fn, code):
        d = copy.deepcopy(ndoc)
        fn(d)
        probs, _ = problems(bdoc, d)
        cases.append((name, code, probs))

    mutate("drop the record for a none check",
           lambda d: d.__setitem__("checks", [e for e in d["checks"] if e["check"] != "S7"]), "N1")
    mutate("record for a check that is not none",
           lambda d: d["checks"].append({"check": "S10", "name": "x", "status": "no-external-text-found",
                                         "searches": [{"query": "q", "on": "2026-11-25", "result": "r"}]}),
           "N1")
    mutate("no searches at all",
           lambda d: d["checks"][0].__setitem__("searches", []), "N2")
    mutate("proposal claimed, no file",
           lambda d: next(e for e in d["checks"] if e["check"] == "S7").__setitem__(
               "proposal", "basis/proposals/does-not-exist.md"), "N3")
    mutate("external basis with no URL",
           lambda d: next(e for e in d["checks"] if e["check"] == "S12").__setitem__("nearest", {"doc": "x"}),
           "N4")
    ok = True
    for name, code, probs in cases:
        hit = any(p.startswith(code) for p in probs)
        print(f"  {'ok' if hit else '!!'} {name} -> expected {code}, got "
              f"{sorted({p.split(':')[0] for p in probs}) or 'nothing'}")
        ok = ok and hit
    return 0 if ok else 1


def main(argv):
    bdoc, ndoc = load(BASIS), load(NONE)
    if "--selftest" in argv:
        rc = selftest(bdoc, ndoc)
        print(f"NONE SELFTEST {'OK' if rc == 0 else 'FAILED'} - 5 record(s) judged as expected.")
        return rc
    probs, none_ids = problems(bdoc, ndoc)
    before = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    render(bdoc, ndoc, none_ids)
    if "--write" not in argv and before != OUT.read_text(encoding="utf-8"):
        print("  !! NONE.md was stale; rewritten. Re-run to confirm.")
        return 1
    if probs:
        print(f"NONE FAILED - {len(probs)} problem(s):")
        for p in probs:
            print(f"  !! {p}")
        return 1
    drafted = sum(1 for e in ndoc["checks"] if e.get("status") == "proposal-drafted")
    found = sum(1 for e in ndoc["checks"] if e.get("status") == "external-basis-found")
    print(f"NONE OK - {len(none_ids)} none check(s), each with a recorded search; "
          f"{found} with an external basis found, {drafted} with a proposal drafted.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
