"""Publish which of the nineteen checks we invented and which somebody else did.

    python tools/basis_map.py            # rewrite BASIS.md and basis.json
    python tools/basis_map.py --check    # fail on any byte difference

The question this answers is the first one a reviewer asks about a corpus that
grades itself: *says who?* Every check in the verifier carries a `basis`
{class, citation}: `direct` means an external document states the requirement,
`related` means the mechanism is borrowed from one, `none` means it is our
design choice. Those three answers are not equally strong, and a corpus that
publishes only the total "19 checks" invites a reader to assume all nineteen
were mandated.

So the counts are published with the split, every citation is resolved through
`basis/sources.json` (a URL fetched on a date, not a name), and the gate refuses:

  B1  a class outside {direct, related, none}
  B2  a `direct` or `related` check with no citation, or a `none` check that
      cites something - "we invented it" and "somebody required it" cannot both
      be true of one rule
  B3  a citation that is not in basis/sources.json: a basis nobody can look up
      is a word, not a basis
  B4  a published count that differs from the measured one, or a split that does
      not sum to nineteen

`--check` is the fourth wall: BASIS.md cannot drift from the verifier's own
report without turning the gate red.
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import coverage_map as cm  # noqa: E402 - one definition of "run the verifier"
import run_vectors as rv  # noqa: E402

SOURCES = os.path.join(ROOT, "basis", "sources.json")
MD = os.path.join(ROOT, "BASIS.md")
JSON = os.path.join(ROOT, "basis.json")
CLASSES = ("direct", "related", "none")
CLASS_MEANING = {
    "direct": "an external document states this requirement; the citation names it",
    "related": "the mechanism is borrowed from an external document; the requirement is ours",
    "none": "our own design choice, with no external text behind it",
}


def sources():
    with open(SOURCES, encoding="utf-8") as fh:
        return json.load(fh)["sources"]


def measure():
    """Ask the verifier what each check says about its own basis.

    Union across every row, not one row: no single package emits all nineteen
    (S19 needs a state file, S16 needs the token), and a table built from one
    package would silently publish a partition of eighteen. Two rows disagreeing
    about the basis of the same check is a defect, so it is reported rather than
    averaged.
    """
    per = {}
    conflicts = []
    for case, extra, _rc, _want in rv.ROWS:
        doc = cm.verify(case, extra)
        for c in doc.get("checks", []):
            b = c.get("basis") or {}
            rec = {"name": c.get("name", ""), "class": b.get("class"),
                   "citation": b.get("citation") or "", "note": b.get("note") or ""}
            prev = per.get(c["id"])
            if prev and (prev["class"], prev["citation"]) != (rec["class"], rec["citation"]):
                conflicts.append((case, c["id"], prev, rec))
            per.setdefault(c["id"], rec)
    return per, conflicts


def problems_for(per, src):
    out = []
    if len(per) != 19:
        out.append(f"B4: the verifier reported {len(per)} checks, the specification names 19")
    for cid, b in per.items():
        if b["class"] not in CLASSES:
            out.append(f"B1: {cid} declares basis {b['class']!r}, not one of {CLASSES}")
            continue
        if b["class"] in ("direct", "related") and not b["citation"]:
            out.append(f"B2: {cid} claims a {b['class']} basis with no citation")
        if b["class"] == "none" and b["citation"]:
            out.append(f"B2: {cid} says its basis is none yet cites {b['citation']!r} - "
                       f"one of those two statements is false")
        if b["citation"] and b["citation"] not in src:
            out.append(f"B3: {cid} cites {b['citation']!r}, which is not in basis/sources.json")
    return out


def render(per, src):
    order = sorted(per, key=lambda c: int(c[1:]) if c[1:].isdigit() else 999)
    counts = {k: sum(1 for b in per.values() if b["class"] == k) for k in CLASSES}
    draft = [cid for cid, b in per.items() if b["citation"]
             and src.get(b["citation"], {}).get("kind") == "draft"]

    lines = [
        "# Basis — which checks somebody else required, and which we chose",
        "",
        "Generated by `tools/basis_map.py` from the verifier's own report. "
        "`python tools/basis_map.py --check` rebuilds it and fails on any byte "
        "difference, so this table cannot drift from the thing it describes.",
        "",
        f"**{counts['direct']} direct · {counts['related']} related · {counts['none']} ours** "
        f"— nineteen total.",
        "",
        "| class | what it means | checks |",
        "|---|---|---|",
    ]
    for k in CLASSES:
        lines.append(f"| `{k}` | {CLASS_MEANING[k]} | {counts[k]} |")
    lines += [
        "",
        "A `direct` basis is the strongest of the three and the easiest to overstate, "
        "so every citation resolves through `basis/sources.json`, where each entry "
        "carries the URL fetched on a stated date. A citation that is not there "
        "fails the gate. A `none` check that cites something also fails: \"we "
        "invented it\" and \"somebody required it\" cannot both be true of one rule.",
        "",
        "| check | name | basis | citation | document |",
        "|---|---|---|---|---|",
    ]
    for cid in order:
        b = per[cid]
        cit = b["citation"] or "—"
        if b["citation"]:
            s = src[b["citation"]]
            doc = f"[{s['kind']}]({s['url']})"
        else:
            doc = "—"
        lines.append(f"| {cid} | {b['name']} | `{b['class']}` | {cit} | {doc} |")

    if draft:
        lines += [
            "",
            f"**{len(draft)} of the citations are individual Internet-Drafts "
            f"({', '.join(sorted(draft))}).** A draft is a proposal by named authors, "
            "not a consensus standard: \"direct\" here means the draft text states "
            "the requirement, and it does not mean a published standard does. That "
            "distinction is the difference between citing a proposal and citing a "
            "rule, and it is the one a reader should check before quoting a count.",
        ]

    lines += [
        "",
        "## What this table does not say",
        "",
        "It does not say the `direct` checks are implemented correctly - that is what "
        "the corpus and the adversarial cases are for. It does not say the `none` "
        "checks are wrong to exist: a format needs behaviour no draft has specified "
        "yet, and inventing it openly is better than attributing it to a document "
        "that does not say it. It says only which of the two happened, per rule.",
        "",
    ]
    doc = "\n".join(lines)
    data = {
        "contract": "uibc-basis-map/1",
        "counts": counts,
        "checks": [{"id": cid, "name": per[cid]["name"], "class": per[cid]["class"],
                    "citation": per[cid]["citation"]} for cid in order],
        "draft_citations": sorted(draft),
    }
    return doc, data


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    per, conflicts = measure()
    src = sources()
    problems = problems_for(per, src)
    for case, cid, prev, rec in conflicts:
        problems.append(f"B5: {cid} declares basis {prev['class']}/{prev['citation']!r} in one "
                        f"row and {rec['class']}/{rec['citation']!r} on {case}")
    if problems:
        print(f"BASIS FAILED - {len(problems)} problem(s):")
        for p in problems:
            print(f"  !! {p}")
        return 1
    doc, data = render(per, src)

    if a.check:
        for path, want in ((MD, doc), (JSON, json.dumps(data, indent=2, sort_keys=True) + "\n")):
            if not os.path.isfile(path):
                print(f"BASIS FAILED - {os.path.basename(path)} is missing; a published "
                      f"split that is not published is not a split")
                return 1
            with open(path, encoding="utf-8") as fh:
                got = fh.read()
            if got != want:
                print(f"BASIS FAILED - {os.path.basename(path)} does not match the "
                      f"verifier's report; regenerate with tools/basis_map.py")
                return 1
        print(f"BASIS OK - {data['counts']['direct']} direct, {data['counts']['related']} "
              f"related, {data['counts']['none']} ours; every citation resolves.")
        return 0

    with open(MD, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(doc)
    with open(JSON, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(data, indent=2, sort_keys=True) + "\n")
    print(f"WROTE BASIS.md and basis.json - {data['counts']['direct']} direct, "
          f"{data['counts']['related']} related, {data['counts']['none']} ours.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
